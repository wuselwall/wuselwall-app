import fs from 'node:fs';
import path from 'node:path';
import { inventory, root } from './matrix.mjs';

const lib = path.join(root, 'app/lib');
const widgets = [...new Set(inventory.states.map(s => s.widget))].sort();
const dartSources = fs.readdirSync(lib, { recursive: true }).filter(n => n.endsWith('.dart'))
  .map(name => ({ name, text: fs.readFileSync(path.join(lib, name), 'utf8') }));
const imports = widgets.map(widget => {
  const matches = dartSources.filter(s => new RegExp(`\\bclass ${widget}\\s`).test(s.text));
  if (matches.length !== 1) throw new Error(`Expected one widget declaration for ${widget}, found ${matches.length}`);
  return `import 'package:wuselwall/${matches[0].name}';`;
});
export const source = '// Generated by qualification/generate-native.mjs from the shared inventory.\n'
  + '// Do not edit by hand. This is only imported by test entry points.\n'
  + "import 'package:flutter/widgets.dart';\n"
  + [...new Set(imports)].sort().join('\n') + '\n\n'
  // Concrete type tests also work under dart2js release minification.
  + 'bool isQualificationDestination(Widget widget, String name) => switch (name) {\n'
  + widgets.map(name => `  '${name}' => widget is ${name},`).join('\n')
  + "\n  _ => throw ArgumentError.value(name, 'name'),\n};\n\n"
  + `const qualificationClock = '${inventory.clock}';\n`
  + `const nativeStatesJson = r'''${JSON.stringify(inventory.states.filter(s => s.native), null, 2)}''';\n`;
const target = path.join(root, 'app/qualification/inventory.g.dart');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== source) throw new Error('Native inventory is stale; run node qualification/generate-native.mjs');
} else fs.writeFileSync(target, source);
