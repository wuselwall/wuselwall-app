#!/usr/bin/env bash
# Fills a Flutter web build's font-fallback/ with the Noto shards its engine can ask for
# (NFR-9). The engine fetches a shard only when text needs a glyph the bundled fonts
# lack (an emoji, a Cyrillic or CJK name); flutter_bootstrap.js points it at this origin
# instead of fonts.gstatic.com, so a visitor's browser never contacts Google.
#
# The shards are pinned by SHA-256 in scripts/web-font-fallback.lock. The list comes from
# the build itself (main.dart.js names every shard), so a Flutter update that changes it
# fails here until the lock is regenerated:
#   scripts/web-font-fallback.sh --update app/build/<web build>
# Usage: scripts/web-font-fallback.sh <web build dir>
set -euo pipefail

update=false
if [[ ${1:-} == --update ]]; then update=true; shift; fi
build=$(cd "${1:?usage: scripts/web-font-fallback.sh [--update] <web build dir>}" && pwd)
cd "$(dirname "$0")/.."

lock=scripts/web-font-fallback.lock
source_url=https://fonts.gstatic.com/s
cache=${WW_FONT_FALLBACK_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/wuselwall/font-fallback}

[[ -f $build/main.dart.js ]] || { echo "no main.dart.js in $build" >&2; exit 1; }

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }

wanted=$(grep -oE '"noto[a-z0-9]+/v[0-9]+/[A-Za-z0-9_.-]+\.(woff2|ttf|otf)"' "$build/main.dart.js" | tr -d '"' | sort -u)
[[ -n $wanted ]] || { echo "main.dart.js names no font fallback shard; has Flutter changed its format?" >&2; exit 1; }

if ! $update; then
  pinned=$(grep -v '^#' "$lock" | awk '{print $2}' | sort -u)
  if [[ $wanted != "$pinned" ]]; then
    echo "The build's font fallback shards differ from $lock:" >&2
    diff <(echo "$pinned") <(echo "$wanted") | grep '^[<>]' | head -20 >&2
    echo "Regenerate with: scripts/web-font-fallback.sh --update $build" >&2
    exit 1
  fi
fi

# Shards are fetched once into the cache (keyed by path, checked by hash on every use).
mkdir -p "$cache"
fetch() {
  local file="$cache/$1"
  [[ -s $file ]] && return 0
  mkdir -p "$(dirname "$file")"
  curl -fsSL --retry 3 -o "$file.part" "$source_url/$1" && mv "$file.part" "$file"
}
export -f fetch
export cache source_url
echo "$wanted" | xargs -P 16 -I{} bash -c 'fetch "$1"' _ {}

if $update; then
  {
    echo "# Flutter web font fallback shards: SHA-256 and path below $source_url/."
    echo "# Generated by scripts/web-font-fallback.sh --update for $(cd app && flutter --version 2>/dev/null | head -1 | cut -d' ' -f1-2)."
    while read -r path; do echo "$(sha256 "$cache/$path")  $path"; done <<<"$wanted"
  } >"$lock"
  echo "wrote $lock ($(echo "$wanted" | wc -l | tr -d ' ') shards)"
fi

out=$build/font-fallback
grep -v '^#' "$lock" | while read -r hash path; do
  if [[ $(sha256 "$cache/$path") != "$hash" ]]; then
    rm -f "$cache/$path"
    echo "font fallback shard $path does not match $lock" >&2
    exit 1
  fi
  mkdir -p "$out/$(dirname "$path")"
  cp "$cache/$path" "$out/$path"
done
echo "font-fallback: $(grep -vc '^#' "$lock") shards in $out"
