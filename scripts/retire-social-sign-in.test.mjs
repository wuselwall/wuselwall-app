// node --test scripts/retire-social-sign-in.test.mjs
// infra/supabase/retire-social-sign-in.sh on the .env of a compose stack set up before social
// sign-in was removed (made by the old make-env.mjs, Google and Apple configured).
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

const script = path.join(path.dirname(new URL(import.meta.url).pathname), '../infra/supabase/retire-social-sign-in.sh');

const OLD_ENV = `# WuselWall compose stack. Generated by infra/supabase/make-env.mjs; secrets — never commit.
SITE_URL='https://app.example.org/'
ADDITIONAL_REDIRECT_URLS='https://app.example.org/**,ch.goomba.wuselwall://login-callback/'
JWT_SECRET='keep-me'
APPLE_ENABLED='true'
APPLE_CLIENT_IDS='org.example.signin,ch.goomba.wuselwall'
APPLE_SECRET='eyJ.apple-login-client-secret.jwt'
GOOGLE_ENABLED='true'
GOOGLE_CLIENT_IDS='web.apps.googleusercontent.com,ios.apps.googleusercontent.com'
GOOGLE_CLIENT_SECRET='google-oauth-secret'
APPLE_TEAM_ID='TEAM123456'
APPLE_KEY_ID='KEY1234567'
APPLE_PRIVATE_KEY='-----BEGIN-----\\nabc\\n-----END-----'
APPLE_CLIENT_ID='ch.goomba.wuselwall'
APPLE_TOKEN_KEY='AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8='
GOOGLE_PROJECT_ID='unused'
`;

/** Writes `content` to a fresh 600 .env, runs the script; returns the file, its text, the log. */
function run(content) {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'retire-')), '.env');
  fs.writeFileSync(file, content, { mode: 0o600 });
  return { file, ...again(file) };
}

function again(file) {
  // The script logs to stderr; fold it into the captured output.
  const log = execFileSync('sh', ['-c', 'sh "$0" "$1" 2>&1', script, file], { encoding: 'utf8' });
  return { log, out: fs.readFileSync(file, 'utf8'), mode: fs.statSync(file).mode & 0o777 };
}

test('removes every Apple and Google value and the native callback, keeps everything else', () => {
  const { out, mode } = run(OLD_ENV);
  for (const k of ['APPLE_ENABLED', 'APPLE_CLIENT_IDS', 'APPLE_SECRET', 'GOOGLE_ENABLED', 'GOOGLE_CLIENT_IDS', 'GOOGLE_CLIENT_SECRET',
    'APPLE_TEAM_ID', 'APPLE_KEY_ID', 'APPLE_PRIVATE_KEY', 'APPLE_CLIENT_ID', 'APPLE_TOKEN_KEY']) {
    assert.doesNotMatch(out, new RegExp(`^${k}=`, 'm'), k);
  }
  assert.match(out, /^ADDITIONAL_REDIRECT_URLS='https:\/\/app\.example\.org\/\*\*'$/m);
  assert.doesNotMatch(out, /login-callback/);
  // Unrelated settings, the upstream Google placeholder included, stay byte for byte.
  const keep = /^(JWT_SECRET|SITE_URL|GOOGLE_PROJECT_ID)=/;
  for (const line of OLD_ENV.split('\n').filter((l) => keep.test(l))) {
    assert.ok(out.split('\n').includes(line), line);
  }
  assert.ok(out.startsWith('# WuselWall compose stack.'));
  assert.equal(mode, 0o600, 'the .env stays readable by its owner only');
});

test('prints names only, never a value', () => {
  const { log } = run(OLD_ENV);
  assert.match(log, /removed APPLE_SECRET/);
  assert.match(log, /removed GOOGLE_CLIENT_SECRET/);
  assert.match(log, /removed the native OAuth callback/);
  assert.match(log, /removed APPLE_TOKEN_KEY/);
  for (const value of ['apple-login-client-secret', 'google-oauth-secret', 'googleusercontent', 'keep-me', 'TEAM123456', 'AAECAwQF']) {
    assert.ok(!log.includes(value), value);
  }
});

test('a second run changes nothing', () => {
  const first = run(OLD_ENV);
  const second = again(first.file);
  assert.equal(second.out, first.out);
  assert.match(second.log, /nothing left to retire/);
});

test('a fresh .env from the current make-env.mjs is left alone', () => {
  const fresh = "SITE_URL='https://app.example.org/'\nADDITIONAL_REDIRECT_URLS='https://app.example.org/**'\nGOOGLE_PROJECT_ID='unused'\n";
  const { out, log } = run(fresh);
  assert.equal(out, fresh);
  assert.match(log, /nothing left to retire/);
});

test('a mixed redirect list loses only the native callback, other entries keep their order', () => {
  const mixed = "ADDITIONAL_REDIRECT_URLS='https://app.example.org/**,https://app.example.org/invite/**,"
    + "ch.goomba.wuselwall://login-callback/,https://app.example.org/pair/**,"
    + "https://app.example.org/help/login-callback-faq'\n";
  const { file, out } = run(mixed);
  assert.equal(out, "ADDITIONAL_REDIRECT_URLS='https://app.example.org/**,https://app.example.org/invite/**,"
    + "https://app.example.org/pair/**,https://app.example.org/help/login-callback-faq'\n");
  const second = again(file);
  assert.equal(second.out, out);
  assert.match(second.log, /nothing left to retire/);
});
