import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { readdirSync } from 'node:fs';
import { fold, loadDictionary, normalize, parseSource, renderDomain, renderJson, sqlMigration } from './dictionary.mjs';

const root = new URL('../', import.meta.url);
const read = (file) => readFileSync(new URL(file, root), 'utf8');

test('fold lower-cases and replaces umlauts, sharp s and accents', () => {
  assert.equal(fold('Äpfel Öl Über Straße'), 'aepfel oel ueber strasse');
  assert.equal(fold('ÁÀÂÉÈÊÍÌÎÓÒÔÚÙÛÑÇ'), 'aaaeeeiiiooouuunc');
  assert.equal(fold('Œuf'), 'œuf');
});

test('normalize folds and collapses runs of other characters to one space', () => {
  assert.equal(normalize('WC-Papier'), 'wc papier');
  assert.equal(normalize("Jus d'orange"), 'jus d orange');
  assert.equal(normalize('Crème fraîche'), 'creme fraiche');
  assert.equal(normalize('  Mac & Cheese!! '), 'mac cheese');
  assert.equal(normalize('Rüebli'), 'rueebli');
});

const sample = `# comment
milk -> dairy, other
  de: Milch, Käse-Milch
  de-CH: Rahm
  # inside a block
  fr: Crème fraîche

egg -> dairy
  en: Egg, EGG, eggs
`;

test('parses blocks, arrows, tags and comments', () => {
  const blocks = parseSource(sample, 'shopping');
  assert.deepEqual(blocks.map((b) => [b.key, b.categories]), [['milk', ['dairy', 'other']], ['egg', ['dairy']]]);
  assert.deepEqual(blocks[0].tags, { de: ['Milch', 'Käse-Milch'], 'de-CH': ['Rahm'], fr: ['Crème fraîche'] });
  assert.deepEqual(renderDomain(blocks, 'shopping').entries, [
    { key: 'milk', categories: ['dairy', 'other'], words: ['creme fraiche', 'kaese milch', 'milch', 'rahm'] },
    { key: 'egg', categories: ['dairy'], words: ['egg', 'eggs'] },
  ]);
});

test('a word in two keys throws and names both', () => {
  const blocks = parseSource('a\n  de: Tee\nb\n  en: tee, x\n', 'meals');
  assert.throws(() => renderDomain(blocks, 'meals'), /"tee".*"a".*"b"/);
});

test('invalid sources throw with file:line', () => {
  assert.throws(() => parseSource('a\n  xx: word\n', 'meals', 'm.txt'), /m\.txt:2: unknown tag "xx"/);
  assert.throws(() => parseSource('a\n  de: one, , two\n', 'meals', 'm.txt'), /m\.txt:2: empty word/);
  assert.throws(() => parseSource('a\nb\n  de: x\n', 'meals', 'm.txt'), /m\.txt:1: block "a" has no words/);
  assert.throws(() => parseSource('a\n  de: x\na\n  de: y\n', 'meals', 'm.txt'), /m\.txt:3: duplicate block "a"/);
  assert.throws(() => parseSource('a -> nope\n  de: x\n', 'shopping', 's.txt'), /s\.txt:1: unknown category "nope"/);
  assert.throws(() => parseSource('a -> dairy\n  de: x\n', 'meals', 'm.txt'), /only allowed in the shopping domain/);
});

test('a picture may head several blocks, told apart by a suffix', () => {
  const blocks = parseSource('fries -> snacks, frozen\n  de: Chips\nfries.frozen -> frozen, snacks\n  de: Pommes\n', 'shopping');
  assert.deepEqual(blocks.map((b) => [b.id, b.key, b.categories]), [['fries', 'fries', ['snacks', 'frozen']], ['fries.frozen', 'fries', ['frozen', 'snacks']]]);
  assert.deepEqual(renderDomain(blocks, 'shopping').entries.map((e) => e.key), ['fries', 'fries']);
  assert.throws(() => renderDomain(parseSource('a\n  de: x\na.b\n  de: x\n', 'meals'), 'meals'), /"x".*"a".*"a\.b"/);
  assert.throws(() => parseSource('a.b\n  de: x\na.b\n  de: y\n', 'meals', 'm.txt'), /m\.txt:3: duplicate block "a\.b"/);
});

test('a @ key needs categories and no picture', () => {
  assert.throws(() => parseSource('@tools\n  de: Hammer\n', 'shopping', 's.txt'), /s\.txt:1: block "@tools" has no picture, so it needs categories/);
  const blocks = parseSource('@tools -> tools\n  de: Hammer\n', 'shopping');
  assert.deepEqual(renderDomain(blocks, 'shopping').entries, [{ key: '@tools', categories: ['tools'], words: ['hammer'] }]);
});

test('the sql migration fills app.match_word with every domain, sorted, quoted', () => {
  const sql = sqlMigration({ domains: {
    shopping: { entries: [{ key: 'b', categories: ['dairy', 'pantry'], words: ["d'x", 'y'] }, { key: 'a', categories: ['produce'], words: ['z'] }] },
    meals: { entries: [{ key: 'm', categories: [], words: ['w'] }] },
  } });
  assert.match(sql, /^-- Generated by `node scripts\/dictionary.mjs sql`/);
  assert.match(sql, /create table if not exists app\.match_word/);
  assert.match(sql, /delete from app\.match_word;/);
  assert.equal(sql.slice(sql.indexOf('values\n')), [
    'values',
    "  ('shopping', 'z', 'a', '{produce}'),",
    "  ('shopping', 'd''x', 'b', '{dairy,pantry}'),",
    "  ('shopping', 'y', 'b', '{dairy,pantry}'),",
    "  ('meals', 'w', 'm', '{}');",
    '',
  ].join('\n'));
});

const { json } = loadDictionary();
const index = (domain) => new Map(json.domains[domain].entries.flatMap((e) => e.words.map((w) => [w, e.key])));

// Every (word, key) pair of a `with w(word, key) as (values ...)` list in a SQL function.
function sqlPairs(file, fn) {
  const sql = read(file);
  const start = sql.indexOf(`function ${fn}(`);
  assert.ok(start >= 0, `${fn} not found in ${file}`);
  const values = sql.slice(start).match(/with w\(word, key\) as \(values([\s\S]*?)\n\s*\),/);
  assert.ok(values, `no values list in ${fn}`);
  const pairs = [...values[1].matchAll(/\('((?:[^']|'')*)', '([a-z_0-9]+)'\)/g)].map((m) => [m[1].replaceAll("''", "'"), m[2]]);
  assert.ok(pairs.length > 100, `${fn}: only ${pairs.length} pairs found`);
  return pairs;
}

// Pairs where the dictionary deliberately (or pending review) files a word under another key than
// the SQL function. The test pins the dictionary's key, so a change in either place shows up.
const differs = {
  shopping: {
    erdnussbutter: 'honey', 'peanut butter': 'honey', // a spread, not nuts
    // cereals have no picture of their own (#196 files them under pantry, the bowl is yoghurt)
    muesli: '@cereal', cornflakes: '@cereal', haferflocken: '@cereal', cereal: '@cereal', porridge: '@cereal', oats: '@cereal',
  },
  meals: { gratin: 'pie', parmentier: 'pie', tostadas: 'sandwich', wedges: 'fries' },
};

for (const [domain, file, fn] of [
  ['shopping', 'supabase/migrations/20261015120000_catalog_icons.sql', 'app.catalog_icon_for'],
  ['meals', 'supabase/migrations/20261025130000_rituals_wishes_story.sql', 'app.meal_icon_for'],
]) {
  test(`the ${domain} dictionary contains every pair of ${fn}`, () => {
    const have = index(domain);
    const wrong = sqlPairs(file, fn)
      .map(([word, key]) => [normalize(word), key])
      .filter(([word, key]) => (differs[domain][word] ?? key) !== have.get(word))
      .map(([word, key]) => `${word}: SQL ${key}, dictionary ${have.get(word) ?? 'missing'}`);
    assert.deepEqual(wrong, []);
  });
}

// The two category lists of #196 (20261031100000): the specific words without a picture and the
// icons' categories. The dictionary's first category must be theirs, except where the dictionary
// decides otherwise on purpose (pinned here, so a change in either place shows up).
const categoryDiffers = {
  studentenfutter: 'pantry', 'trail mix': 'pantry', // nuts are nuts; snacks second
  muelltueten: 'household', // bin bags are household goods first, cleaning second
};
// #196's two lists disagree on the sponge's aisle (detergents cleaning first, the sponge icon
// household first); the dictionary says cleaning. Both kinds of list have only one of the two.
const iconDiffers = { sponge: 'cleaning' };

test('the shopping dictionary keeps the first category of every #196 word', () => {
  const sql = read('supabase/migrations/20261031100000_shopping_snacks_and_categories.sql');
  const body = sql.slice(sql.indexOf('with w(word, keys)'), sql.indexOf('i(icon, keys)'));
  const pairs = [...body.matchAll(/\('([^']+)', array\[([^\]]+)\]\)/g)]
    .map((m) => [normalize(m[1]), m[2].replaceAll("'", '').split(/,\s*/)]);
  assert.ok(pairs.length > 100, `only ${pairs.length} pairs found`);
  const byWord = new Map(json.domains.shopping.entries.flatMap((e) => e.words.map((w) => [w, e])));
  const wrong = pairs
    .filter(([word, keys]) => (categoryDiffers[word] ?? keys[0]) !== byWord.get(word)?.categories[0])
    .map(([word, keys]) => `${word}: SQL ${keys.join('/')}, dictionary ${byWord.get(word)?.categories.join('/') ?? 'missing'}`);
  assert.deepEqual(wrong, []);
});

test('the shopping dictionary keeps the first category of every #196 icon', () => {
  const sql = read('supabase/migrations/20261031100000_shopping_snacks_and_categories.sql');
  const body = sql.slice(sql.indexOf('i(icon, keys)'), sql.indexOf('n(whole, last)'));
  const pairs = [...body.matchAll(/\('([a-z_]+)', array\[([^\]]+)\]\)/g)]
    .map((m) => [m[1], m[2].replaceAll("'", '').split(/,\s*/)]);
  assert.ok(pairs.length > 50, `only ${pairs.length} icons found`);
  // The first block of a picture carries its usual categories (fries: crisps, not chips).
  const byKey = new Map();
  for (const e of json.domains.shopping.entries) if (!byKey.has(e.key)) byKey.set(e.key, e.categories);
  const wrong = pairs
    .filter(([icon, keys]) => byKey.get(icon)?.[0] !== (iconDiffers[icon] ?? keys[0]))
    .map(([icon, keys]) => `${icon}: SQL ${keys.join('/')}, dictionary ${byKey.get(icon)?.join('/') ?? 'missing'}`);
  assert.deepEqual(wrong, []);
  for (const e of json.domains.shopping.entries) {
    assert.ok(e.categories.length > 0, `${e.key} has no category`);
  }
});

test('the newest match_words migration is the current render', () => {
  const files = readdirSync(new URL('supabase/migrations/', root)).filter((f) => f.endsWith('_match_words.sql')).sort();
  assert.ok(files.length > 0, 'no *_match_words.sql migration; run: node scripts/dictionary.mjs sql > supabase/migrations/<timestamp>_match_words.sql');
  assert.equal(read(`supabase/migrations/${files.at(-1)}`), sqlMigration(json),
    `supabase/migrations/${files.at(-1)} is stale: write the next *_match_words.sql with node scripts/dictionary.mjs sql`);
});

test('the rendered JSON is deterministic and sorted', () => {
  const again = loadDictionary().json;
  assert.equal(renderJson(again), renderJson(json));
  for (const domain of Object.values(json.domains)) {
    for (const entry of domain.entries) {
      assert.deepEqual(entry.words, [...new Set(entry.words)].sort());
    }
  }
});

test('the committed dictionary.json is up to date', () => {
  assert.equal(read('app/assets/matching/dictionary.json'), renderJson(json));
});
