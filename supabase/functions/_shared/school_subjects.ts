/**
 * The subject words of each language, for the timetable scan (specs/24 "The family's words",
 * research in specs/research/school-subjects/): the full names the curricula use and the short
 * codes the sheets print. The parser uses them for four things: a known subject word is never
 * read as a weekday by guess; a cell's code gets its full name, so the preview shows "SU ·
 * Sachunterricht"; a word the OCR almost read ("Sachunterrlcht") snaps to the real one; and
 * a scanned word with no match in the family's subjects can point at the family's subject of
 * the same group ("HSU" at the family's Sachunterricht), for the preview to offer.
 *
 * Codes are lowercase without accents (as `fold` makes them). A code with several meanings in
 * one language (German "TG": Technisches Zeichnen, Textiles Gestalten, Technisches Gestalten)
 * stands in `ambiguous`: known, but with no name, so the parent names it. Codes of other
 * languages are never consulted; what a code means is a question of the sheet's language.
 *
 * Groups are fine where a coarse one would mislead: every language is its own group, so a
 * scanned "F" never lands on the family's Englisch; the sciences are split the same way.
 */

